/**
 * Phase 2 of the square-rotation audit: do the *shipped* Level 2 solvers cope
 * with states produced by the 54 additional square-ring rotations?
 *
 * Run: `node --import tsx research/square-rotation/solver-trials.ts` from the
 * repo root. Writes `research/square-rotation/out/l2-solver-trials.json`.
 * Set `TRIALS_PILOT=1` for a short smoke run (3 single-move states, one seed
 * per word length) used only to time the harness.
 *
 * Nothing here changes the shipped model. The solvers are driven through
 * `mengerPuzzleModel`, whose `legalMoves` returns the 468 *existing* atoms
 * only, so every solution word lies in `G` by construction. The additional
 * atoms are applied outside the model, via synthetic `TurnTarget`s built by
 * `targetForCells`, exactly as the Phase 1 audit did.
 *
 * Definitions used throughout:
 *   G — the group generated by the 468 existing legal atomic moves.
 *   H — the group generated by those 468 plus the 54 additional atoms.
 *
 * Two independent, *rigorous* non-membership tests are run on every scrambled
 * state before any solver sees it (see `buildInvariants`): a site-orbit test
 * and an orbit-wise permutation-parity test. Both are homomorphic invariants
 * of G, so a state failing either is provably outside G; passing both proves
 * nothing. A solver success, replayed and verified here, is a constructive
 * membership certificate; no finite number of them is a completeness proof.
 */
