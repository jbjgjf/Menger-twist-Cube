import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createSparseGroup, fullAction, orientationFrames, parityBasis, ROT_ID, rotInv, rotMul } from '../../packages/solver-core/src/algorithms/mengerSparseGroup';
import { isThreeCycle } from './tools';
import { level4CertifiedData } from '../../packages/solver-core/src/algorithms/level4CertifiedData';

const level = Number(process.argv.find((a) => a.startsWith('--level='))?.split('=')[1] ?? 4);
const group = createSparseGroup(level, console.log);
const frames = orientationFrames(group);
if (frames.some((f) => ![1, 3, 4, 8].includes(f.freedom.length))) throw new Error('Unexpected orientation subgroup; the current order formula does not cover it');
const records = new Map<number, string[]>();
const candidateData = process.argv.includes('--candidate-data');
if (level === 4 && !candidateData) for (const r of level4CertifiedData.tools) records.set(r.orbit, [...r.word]);
for (const name of level !== 4 || candidateData ? ['tools', 'seed-tools', 'extra-tools'] : []) {
  const file = `research/level4/out/${name}-L${level}.json`;
  if (existsSync(file)) for (const r of JSON.parse(readFileSync(file, 'utf8')).tools) {
    const previous = records.get(r.orbit);
    if (!previous || r.word.length < previous.length) records.set(r.orbit, r.word);
  }
}
const resolve = (ids: readonly string[]) => ids.map((id) => {
  const a = group.atomById.get(id); if (!a) throw new Error(`Unknown atom ${id}`); return a;
});
/**
 * The normal closure of a pure 3-cycle is generated by its conjugate 3-cycles.
 * The components of their support hypergraph are a G-invariant equivalence
 * relation. Close the two edges of the initial support under every generator;
 * one component proves this hypergraph connected, hence its 3-cycles generate
 * Alt(orbit). This also proves independence from the other orbits because
 * every word used is globally pure. Merely seeing Alt in each projection
 * would not justify multiplying the group orders.
 */
const normalClosureConnected = (orbit: number, triple: number[]): boolean => {
  const sites = group.orbits[orbit]!;
  const parent = new Map(sites.map((s) => [s, s]));
  const root = (s: number): number => { while (parent.get(s) !== s) { parent.set(s, parent.get(parent.get(s)!)!); s = parent.get(s)!; } return s; };
  const queue: Array<[number, number]> = [];
  const join = (a: number, b: number): void => {
    const ra = root(a); const rb = root(b);
    if (ra === rb) return;
    parent.set(ra, rb); queue.push([a, b]);
  };
  join(triple[0]!, triple[1]!); join(triple[0]!, triple[2]!);
  for (let head = 0; head < queue.length; head++) {
    const [a, b] = queue[head]!;
    const gens = new Set([...group.atomsAt[a]!, ...group.atomsAt[b]!]);
    for (const gi of gens) { const g = group.atoms[gi]!; join(g.map.get(a) ?? a, g.map.get(b) ?? b); }
  }
  return queue.length === sites.length - 1;
};
const covered: number[] = [];
for (const [orbit, ids] of [...records].sort((a, b) => a[0] - b[0])) {
  const action = fullAction(resolve(ids));
  if (!isThreeCycle(group, orbit, action)) throw new Error(`Orbit ${orbit}: word is not a globally pure 3-cycle`);
  if (!normalClosureConnected(orbit, [...action.keys()])) throw new Error(`Orbit ${orbit}: normal closure is not transitive`);
  covered.push(orbit);
}
console.log(`Independent alternating subgroups certified: ${covered.length}/${group.orbits.length}`);
const orderOf = (r: number): number => { let x = r; let n = 1; while (x !== ROT_ID) { x = rotMul[r]![x]!; n++; } return n; };
const cyclic = frames.map((f) => {
  const q = f.freedom.find((r) => orderOf(r) === 4);
  return f.freedom.length === 8 ? new Set([ROT_ID, q!, rotMul[q!]![q!]!, rotInv[q!]!]) : new Set(f.freedom);
});
const c3Logs = frames.map((f) => {
  const q = f.freedom.find((r) => r !== ROT_ID);
  return f.freedom.length === 3 ? new Map([[ROT_ID, 0], [q!, 1], [rotMul[q!]![q!]!, 2]]) : null;
});
const twist = (orbit: number, site: number, to: number, rotation: number): number =>
  rotMul[rotInv[frames[orbit]!.ref[to]!]!]![rotMul[rotation]![frames[orbit]!.ref[site]!]!]!;
let invariantChecks = 0;
for (const atom of group.atoms) {
  const sums = new Map<number, number>();
  for (const [site, to] of atom.map) {
    const orbit = group.orbitOf[site]!;
    const order = frames[orbit]!.freedom.length;
    if (order !== 3 && order !== 8) continue;
    const r = twist(orbit, site, to, atom.rot);
    const value = order === 3 ? c3Logs[orbit]!.get(r) : Number(!cyclic[orbit]!.has(r));
    if (value === undefined) throw new Error('Atom leaves the orientation frame');
    sums.set(orbit, (sums.get(orbit) ?? 0) + value);
  }
  for (const [orbit, sum] of sums) {
    invariantChecks++;
    if (sum % (frames[orbit]!.freedom.length === 3 ? 3 : 2)) throw new Error(`Orientation invariant failed: ${atom.id}, orbit ${orbit}`);
  }
}
let rollCells = 0;
for (const [orbit, f] of frames.entries()) {
  if (f.freedom.length !== 4 && f.freedom.length !== 8) continue;
  for (const s of group.orbits[orbit]!) {
    const have = new Set(group.atomsAt[s]!.map((i) => group.atoms[i]!).filter((a) => a.map.size === 1 && a.map.get(s) === s).map((a) => twist(orbit, s, s, a.rot)));
    for (const r of cyclic[orbit]!) if (r !== ROT_ID && !have.has(r)) throw new Error(`No independent roll at site ${s}`);
    rollCells++;
  }
}
const oPath = `research/level4/out/orientation-tools-L${level}.json`;
const pairRecords: Array<{ orbit: number; kind: string; word: readonly string[] }> = level === 4 && !candidateData ? [...level4CertifiedData.pairTwisters]
  : existsSync(oPath) ? JSON.parse(readFileSync(oPath, 'utf8')).tools : [];
const verifiedPairs = new Set<number>();
for (const t of pairRecords) {
  const action = fullAction(resolve(t.word));
  if (action.size !== 2 || [...action].some(([s, [to]]) => s !== to || group.orbitOf[s] !== t.orbit)) throw new Error(`Bad pair twister ${t.orbit}`);
  if (t.kind === 'C3') {
    const sum = [...action].reduce((n, [s, [, r]]) => n + c3Logs[t.orbit]!.get(twist(t.orbit, s, s, r))!, 0);
    if (sum % 3) throw new Error('Non-zero C3 twist sum');
  } else if ([...action].some(([s, [, r]]) => cyclic[t.orbit]!.has(twist(t.orbit, s, s, r)))) throw new Error('D4 pair does not flip both cells');
  verifiedPairs.add(t.orbit);
}
const rank = parityBasis(group).length;
const factorial = (n: number): bigint => { let v = 1n; for (let k = 2; k <= n; k++) v *= BigInt(k); return v; };
let positionLowerOrder = 2n ** BigInt(rank);
for (const oi of covered) positionLowerOrder *= factorial(group.orbits[oi]!.length) / 2n;
// All independent rolls are certified even if a few position orbits remain open.
let orientationLowerOrder = 4n ** BigInt(rollCells);
for (const oi of verifiedPairs) if (covered.includes(oi)) {
  const n = group.orbits[oi]!.length;
  orientationLowerOrder *= frames[oi]!.freedom.length === 3 ? 3n ** BigInt(n - 1) : 2n ** BigInt(n - 1);
}
const groupLowerOrder = positionLowerOrder * orientationLowerOrder;
const log10 = (v: bigint): number => { const s = v.toString(); return s.length - 1 + Math.log10(Number(`${s[0]}.${s.slice(1, 16)}`)); };
const countingBound = (v: bigint): number => {
  const M = BigInt(group.atoms.length);
  let d = Math.ceil(log10(v) / Math.log10(group.atoms.length));
  const ball = (r: number): bigint => (M ** BigInt(r + 1) - 1n) / (M - 1n);
  while (d > 0 && ball(d - 1) >= v) d--;
  while (ball(d) < v) d++;
  return d;
};
const neededPairs = frames.filter((f) => f.freedom.length === 3 || f.freedom.length === 8).length;
const complete = covered.length === group.orbits.length && verifiedPairs.size === neededPairs;
const verifiedData = { tools: [...records].sort((a, b) => a[0] - b[0]).map(([orbit, word]) => ({ orbit, word })), pairTwisters: pairRecords };
const report = {
  schema: 1, level, cells: group.N, legalAtoms: group.atoms.length,
  independentAlternatingOrbits: covered.length, totalOrbits: group.orbits.length,
  missingOrbits: group.orbits.flatMap((_, i) => covered.includes(i) ? [] : [i]),
  parityRank: rank, orientationInvariantChecks: invariantChecks, independentRollCells: rollCells,
  pairTwisters: verifiedPairs.size, pairTwistersRequired: neededPairs,
  completeGroupOrderCertificate: complete,
  wordDataSha256: createHash('sha256').update(JSON.stringify(verifiedData)).digest('hex'),
  log10PositionLowerOrder: log10(positionLowerOrder), log10OrientationLowerOrder: log10(orientationLowerOrder), log10GroupLowerOrder: log10(groupLowerOrder),
  groupLowerOrderDigits: groupLowerOrder.toString().length,
  groupLowerOrderSha256: createHash('sha256').update(groupLowerOrder.toString()).digest('hex'),
  godsNumberLowerBound: countingBound(groupLowerOrder),
};
mkdirSync('research/level4/out', { recursive: true });
writeFileSync(`research/level4/out/certificate-L${level}.json`, JSON.stringify(report, null, 2) + '\n');
writeFileSync(`research/level4/out/merged-tools-L${level}.json`, JSON.stringify({ level, ...verifiedData }) + '\n');
writeFileSync(`research/level4/out/orbits-L${level}.csv`, 'orbit,size,freedom_order,base_x,base_y,base_z,tool_length\n' + group.orbits.map((sites, orbit) =>
  [orbit, sites.length, frames[orbit]!.freedom.length, ...group.sites[sites[0]!]!, records.get(orbit)?.length ?? ''].join(',')).join('\n') + '\n');
console.log(JSON.stringify(report, null, 2));
