import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const certificate = JSON.parse(readFileSync('research/level4/out/certificate-L4.json', 'utf8'));
if (!certificate.completeGroupOrderCertificate) throw new Error('Cannot export an incomplete certificate');
const verified = JSON.parse(readFileSync('research/level4/out/merged-tools-L4.json', 'utf8'));
const tools: Array<{ orbit: number; word: string[] }> = verified.tools;
const pairTwisters: Array<{ orbit: number; kind: string; word: readonly string[] }> = verified.pairTwisters;
if (tools.length !== 3050 || pairTwisters.length !== 9) throw new Error('Verified tool data is incomplete');
if (createHash('sha256').update(JSON.stringify({ tools, pairTwisters })).digest('hex') !== certificate.wordDataSha256) throw new Error('Verified data hash differs from its certificate');
const alphabet = [...new Set([...tools, ...pairTwisters].flatMap((t) => t.word))].sort();
const index = new Map(alphabet.map((a, i) => [a, i]));
const encoded = tools.map((t) => [t.orbit, ...t.word.map((a) => index.get(a)!)]);
writeFileSync('packages/solver-core/src/algorithms/level4CertifiedData.ts',
  `/* Generated by research/level4/export.ts after all 3,050 independent-orbit certificates pass. */\n` +
  `import type { CertifiedReductionData } from './mengerCertifiedReduction';\n` +
  `const alphabet: string[] = ${JSON.stringify(alphabet)};\n` +
  `const words: number[][] = ${JSON.stringify(encoded)};\n` +
  `export const level4CertifiedData: CertifiedReductionData = {\n` +
  `  tools: words.map(([orbit, ...word]) => ({ orbit: orbit!, word: word.map((i) => alphabet[i]!) })),\n` +
  `  pairTwisters: ${JSON.stringify(pairTwisters)},\n};\n`);
console.log(`Exported ${tools.length} pure cycles and ${pairTwisters.length} pair twisters; ${alphabet.length} distinct atom ids`);
